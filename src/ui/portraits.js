// Procedural wireframe monster portraits. Each draws inside (x,y,w,h) using
// normalized [0..1] coordinates — pure line art, true to the era.

export function drawPortrait(ctx, id, x, y, w, h, color) {
  ctx.save();
  ctx.strokeStyle = color;
  ctx.lineWidth = 1.5;
  const X = nx => x + nx * w;
  const Y = ny => y + ny * h;
  const poly = (pts, close = false) => {
    ctx.beginPath();
    ctx.moveTo(X(pts[0][0]), Y(pts[0][1]));
    for (let i = 1; i < pts.length; i++) ctx.lineTo(X(pts[i][0]), Y(pts[i][1]));
    if (close) ctx.closePath();
    ctx.stroke();
  };
  const ell = (cx, cy, rx, ry, a0 = 0, a1 = Math.PI * 2) => {
    ctx.beginPath();
    ctx.ellipse(X(cx), Y(cy), rx * w, ry * h, 0, a0, a1);
    ctx.stroke();
  };
  const dot = (cx, cy, r = 0.015) => { ctx.beginPath(); ctx.arc(X(cx), Y(cy), r * w, 0, Math.PI * 2); ctx.stroke(); };

  const fns = {
    rat() {
      ell(0.5, 0.62, 0.3, 0.2);                 // body
      ell(0.76, 0.45, 0.14, 0.11);              // head
      poly([[0.86, 0.4], [0.97, 0.36]]);        // snout whisker
      poly([[0.84, 0.49], [0.97, 0.5]]);
      ell(0.72, 0.33, 0.05, 0.05);              // ear
      dot(0.8, 0.42);
      poly([[0.2, 0.66], [0.04, 0.5], [0.1, 0.3]]); // tail
      poly([[0.4, 0.82], [0.4, 0.92]]); poly([[0.6, 0.82], [0.6, 0.92]]);
    },
    beetle() {
      ell(0.5, 0.55, 0.26, 0.3);
      poly([[0.5, 0.25], [0.5, 0.85]]);
      ell(0.5, 0.22, 0.1, 0.08);
      poly([[0.44, 0.16], [0.34, 0.04]]); poly([[0.56, 0.16], [0.66, 0.04]]);
      for (const s of [-1, 1]) {
        poly([[0.5 + s * 0.24, 0.4], [0.5 + s * 0.42, 0.3]]);
        poly([[0.5 + s * 0.26, 0.55], [0.5 + s * 0.46, 0.55]]);
        poly([[0.5 + s * 0.24, 0.7], [0.5 + s * 0.42, 0.84]]);
      }
    },
    hound() {
      poly([[0.15, 0.75], [0.2, 0.5], [0.45, 0.45], [0.7, 0.5], [0.78, 0.35], [0.95, 0.38], [0.92, 0.5], [0.75, 0.62], [0.7, 0.78]]);
      poly([[0.78, 0.35], [0.74, 0.22], [0.7, 0.35]]);     // ear
      poly([[0.95, 0.38], [0.88, 0.46]]);                  // jaw
      dot(0.84, 0.38);
      poly([[0.25, 0.74], [0.25, 0.92]]); poly([[0.6, 0.74], [0.6, 0.92]]);
      poly([[0.15, 0.75], [0.04, 0.6]]);                   // tail
      for (let i = 0; i < 3; i++) poly([[0.86 + i * 0.03, 0.46], [0.85 + i * 0.03, 0.52]]); // teeth
    },
    spider() {
      ell(0.5, 0.6, 0.16, 0.18);
      ell(0.5, 0.36, 0.1, 0.09);
      dot(0.46, 0.33); dot(0.54, 0.33); dot(0.5, 0.3);
      for (const s of [-1, 1]) for (let i = 0; i < 4; i++) {
        const yy = 0.42 + i * 0.1;
        poly([[0.5 + s * 0.14, yy], [0.5 + s * 0.34, yy - 0.12], [0.5 + s * 0.46, yy + 0.1]]);
      }
    },
    snake() {
      poly([[0.15, 0.85], [0.3, 0.7], [0.2, 0.55], [0.4, 0.45], [0.3, 0.3], [0.55, 0.25], [0.62, 0.35]]);
      ell(0.68, 0.3, 0.12, 0.09);
      poly([[0.79, 0.27], [0.95, 0.22], [0.9, 0.3], [0.95, 0.34]]); // tongue
      dot(0.7, 0.27);
      poly([[0.15, 0.85], [0.1, 0.92]]);
    },
    zombie() {
      ell(0.5, 0.2, 0.11, 0.12);                 // head, lolling
      poly([[0.44, 0.3], [0.42, 0.5], [0.36, 0.85]]);   // torso line
      poly([[0.56, 0.3], [0.6, 0.5], [0.62, 0.85]]);
      poly([[0.42, 0.38], [0.2, 0.42], [0.12, 0.6]]);   // reaching arm
      poly([[0.6, 0.38], [0.82, 0.36], [0.95, 0.5]]);
      poly([[0.45, 0.16], [0.49, 0.18]]);               // dead eyes
      dot(0.55, 0.17);
      poly([[0.46, 0.26], [0.54, 0.24]]);               // slack mouth
      poly([[0.42, 0.5], [0.6, 0.55]]);                 // torn waist
      poly([[0.36, 0.85], [0.34, 0.95]]); poly([[0.62, 0.85], [0.64, 0.95]]);
    },
    skeleton() {
      ell(0.5, 0.16, 0.1, 0.1);
      poly([[0.46, 0.13], [0.48, 0.16]]); poly([[0.54, 0.13], [0.52, 0.16]]);
      poly([[0.46, 0.22], [0.54, 0.22]]);
      poly([[0.5, 0.26], [0.5, 0.6]]);
      for (let i = 0; i < 4; i++) {
        const yy = 0.32 + i * 0.07;
        poly([[0.5 - 0.12 + i * 0.012, yy], [0.5 + 0.12 - i * 0.012, yy]]);
      }
      poly([[0.5, 0.3], [0.3, 0.36], [0.24, 0.55]]);
      poly([[0.5, 0.3], [0.7, 0.36], [0.78, 0.5], [0.9, 0.42]]); // raised claw
      poly([[0.5, 0.6], [0.4, 0.8], [0.38, 0.95]]);
      poly([[0.5, 0.6], [0.6, 0.8], [0.64, 0.95]]);
    },
    blob() {
      poly([[0.15, 0.85], [0.1, 0.6], [0.25, 0.5], [0.2, 0.32], [0.42, 0.38], [0.5, 0.2], [0.6, 0.36], [0.8, 0.3], [0.74, 0.5], [0.9, 0.62], [0.82, 0.85]], true);
      ell(0.42, 0.55, 0.04, 0.05); ell(0.6, 0.5, 0.05, 0.04);  // bubbles
      ell(0.52, 0.7, 0.06, 0.05);
      poly([[0.5, 0.2], [0.5, 0.08]]);                         // wick!
      poly([[0.47, 0.07], [0.5, 0.0], [0.53, 0.07], [0.5, 0.04]], true); // flame
    },
    wisp() {
      ell(0.5, 0.45, 0.12, 0.14);
      ell(0.5, 0.45, 0.2, 0.24);
      ell(0.5, 0.45, 0.28, 0.34);
      poly([[0.5, 0.79], [0.45, 0.95]]);
      poly([[0.34, 0.6], [0.2, 0.72]]); poly([[0.66, 0.6], [0.8, 0.72]]);
      dot(0.5, 0.45, 0.02);
    },
    brute() {
      ell(0.5, 0.18, 0.1, 0.09);
      poly([[0.3, 0.32], [0.5, 0.26], [0.7, 0.32], [0.74, 0.6], [0.64, 0.62], [0.62, 0.85], [0.38, 0.85], [0.36, 0.62], [0.26, 0.6]], true);
      poly([[0.3, 0.32], [0.14, 0.5], [0.1, 0.72], [0.18, 0.74]]); // arm to ground
      poly([[0.7, 0.32], [0.88, 0.45], [0.93, 0.68], [0.84, 0.72]]);
      dot(0.46, 0.16); dot(0.54, 0.16);
      poly([[0.44, 0.22], [0.56, 0.22]]);
      poly([[0.38, 0.85], [0.36, 0.95]]); poly([[0.62, 0.85], [0.64, 0.95]]);
    },
    humanoid() {
      ell(0.5, 0.16, 0.09, 0.09);
      poly([[0.5, 0.25], [0.5, 0.58]]);
      poly([[0.5, 0.3], [0.32, 0.42], [0.3, 0.55]]);
      poly([[0.5, 0.3], [0.68, 0.4], [0.78, 0.32]]);   // knife arm
      poly([[0.78, 0.32], [0.86, 0.24]]);
      poly([[0.5, 0.58], [0.4, 0.78], [0.38, 0.95]]);
      poly([[0.5, 0.58], [0.6, 0.78], [0.62, 0.95]]);
      poly([[0.41, 0.12], [0.59, 0.12]]);              // hood brim
      dot(0.47, 0.16); dot(0.53, 0.16);
    },
    sorcerer() {
      poly([[0.5, 0.04], [0.4, 0.2], [0.6, 0.2]], true);     // hat
      ell(0.5, 0.26, 0.08, 0.08);
      poly([[0.4, 0.34], [0.36, 0.6], [0.3, 0.92], [0.7, 0.92], [0.64, 0.6], [0.6, 0.34]], true); // robe
      poly([[0.4, 0.4], [0.2, 0.5], [0.16, 0.36]]);          // staff arm
      poly([[0.16, 0.2], [0.16, 0.7]]);                      // staff
      ell(0.16, 0.16, 0.04, 0.04);
      poly([[0.6, 0.4], [0.78, 0.46], [0.88, 0.4]]);
      dot(0.47, 0.25); dot(0.53, 0.25);
      poly([[0.44, 0.31], [0.5, 0.34], [0.56, 0.31]]);       // beard
      poly([[0.46, 0.34], [0.5, 0.44], [0.54, 0.34]]);
    },
    candleking() {
      // crown of seven flames
      for (let i = 0; i < 7; i++) {
        const cx = 0.26 + i * 0.08;
        poly([[cx - 0.02, 0.14], [cx, 0.05], [cx + 0.02, 0.14]]);
      }
      poly([[0.24, 0.14], [0.76, 0.14]]);
      ell(0.5, 0.26, 0.13, 0.1);                       // melted face
      dot(0.45, 0.24); dot(0.56, 0.25);
      poly([[0.46, 0.3], [0.5, 0.33], [0.55, 0.3]]);
      // dripping bulk
      poly([[0.3, 0.36], [0.26, 0.6], [0.18, 0.62], [0.2, 0.9], [0.8, 0.9], [0.82, 0.58], [0.72, 0.6], [0.7, 0.36]], true);
      for (const [dx2, dy2] of [[0.32, 0.5], [0.5, 0.55], [0.66, 0.48]]) {
        poly([[dx2, dy2], [dx2 - 0.02, dy2 + 0.12], [dx2 + 0.02, dy2 + 0.16]]);
      }
      poly([[0.3, 0.36], [0.7, 0.36]]);
    },
    ghost() {
      poly([[0.3, 0.9], [0.28, 0.5], [0.34, 0.25], [0.5, 0.14], [0.66, 0.25], [0.72, 0.5], [0.7, 0.9]]);
      poly([[0.3, 0.9], [0.38, 0.8], [0.46, 0.9], [0.54, 0.8], [0.62, 0.9], [0.7, 0.9]]); // ragged hem
      ell(0.44, 0.3, 0.03, 0.05); ell(0.58, 0.3, 0.03, 0.05);
      ell(0.51, 0.42, 0.05, 0.08);                      // howling mouth
      poly([[0.28, 0.5], [0.1, 0.62]]); poly([[0.72, 0.5], [0.9, 0.62]]);
    },
    hag() {
      ell(0.5, 0.2, 0.1, 0.11);
      poly([[0.4, 0.12], [0.3, 0.04], [0.44, 0.08]]);   // wild hair
      poly([[0.6, 0.12], [0.7, 0.03], [0.56, 0.07]]);
      poly([[0.5, 0.2], [0.56, 0.24], [0.5, 0.26]]);    // hook nose
      dot(0.45, 0.18); dot(0.57, 0.17);
      poly([[0.42, 0.31], [0.4, 0.6], [0.34, 0.92], [0.66, 0.92], [0.6, 0.6], [0.58, 0.31]], true);
      poly([[0.42, 0.38], [0.24, 0.34], [0.12, 0.42]]); // clawed hands
      poly([[0.12, 0.42], [0.06, 0.38]]); poly([[0.12, 0.42], [0.07, 0.46]]);
      poly([[0.58, 0.38], [0.76, 0.34], [0.9, 0.42]]);
      poly([[0.9, 0.42], [0.96, 0.38]]); poly([[0.9, 0.42], [0.95, 0.47]]);
    },
    knight() {
      poly([[0.42, 0.08], [0.58, 0.08], [0.58, 0.22], [0.5, 0.26], [0.42, 0.22]], true); // helm
      poly([[0.44, 0.15], [0.56, 0.15]]);              // visor slit
      poly([[0.5, 0.08], [0.5, 0.0]]);                  // crest
      poly([[0.36, 0.3], [0.64, 0.3], [0.6, 0.62], [0.5, 0.68], [0.4, 0.62]], true); // breastplate
      poly([[0.36, 0.3], [0.2, 0.4], [0.18, 0.62]]);    // shield arm
      poly([[0.1, 0.4], [0.26, 0.4], [0.26, 0.66], [0.18, 0.74], [0.1, 0.66]], true); // shield
      poly([[0.64, 0.3], [0.8, 0.34], [0.84, 0.2]]);    // sword arm
      poly([[0.84, 0.24], [0.84, 0.02]]);               // blade
      poly([[0.8, 0.24], [0.88, 0.24]]);
      poly([[0.5, 0.68], [0.42, 0.95]]); poly([[0.5, 0.68], [0.58, 0.95]]);
    },
    bird() {
      ell(0.5, 0.5, 0.14, 0.2);
      ell(0.5, 0.24, 0.08, 0.08);
      poly([[0.56, 0.24], [0.72, 0.28], [0.56, 0.3]]);  // beak open
      dot(0.48, 0.22);
      poly([[0.38, 0.42], [0.1, 0.25], [0.2, 0.5], [0.38, 0.55]]); // wings
      poly([[0.62, 0.42], [0.9, 0.25], [0.8, 0.5], [0.62, 0.55]]);
      poly([[0.46, 0.7], [0.42, 0.9]]); poly([[0.54, 0.7], [0.58, 0.9]]);
      poly([[0.42, 0.9], [0.36, 0.88]]); poly([[0.58, 0.9], [0.64, 0.88]]);
    },
    choir() {
      for (const [ox, s] of [[0.22, 0.7], [0.5, 1], [0.78, 0.7]]) {
        ell(ox, 0.5 - 0.28 * s + 0.08, 0.06 * s, 0.06 * s);
        poly([[ox - 0.1 * s, 0.9], [ox - 0.08 * s, 0.5 - 0.1 * s], [ox, 0.5 - 0.2 * s + 0.06], [ox + 0.08 * s, 0.5 - 0.1 * s], [ox + 0.1 * s, 0.9]]);
        ell(ox, 0.5 - 0.28 * s + 0.1, 0.018, 0.03); // open mouths
      }
    },
    gargoyle() {
      ell(0.5, 0.24, 0.1, 0.09);
      poly([[0.42, 0.18], [0.36, 0.06]]); poly([[0.58, 0.18], [0.64, 0.06]]); // horns
      dot(0.46, 0.22); dot(0.54, 0.22);
      poly([[0.44, 0.28], [0.5, 0.31], [0.56, 0.28]]);
      poly([[0.4, 0.33], [0.36, 0.6], [0.3, 0.9], [0.7, 0.9], [0.64, 0.6], [0.6, 0.33]], true);
      poly([[0.4, 0.4], [0.12, 0.2], [0.3, 0.5]]);      // stone wings
      poly([[0.6, 0.4], [0.88, 0.2], [0.7, 0.5]]);
      poly([[0.3, 0.9], [0.26, 0.96]]); poly([[0.7, 0.9], [0.74, 0.96]]);
    },
    golem() {
      poly([[0.4, 0.08], [0.6, 0.08], [0.6, 0.24], [0.4, 0.24]], true);
      poly([[0.46, 0.14], [0.54, 0.14]]);
      poly([[0.32, 0.28], [0.68, 0.28], [0.66, 0.66], [0.34, 0.66]], true);
      // runes
      poly([[0.44, 0.36], [0.5, 0.42], [0.44, 0.48]]);
      poly([[0.56, 0.36], [0.56, 0.48]]); dot(0.56, 0.53);
      poly([[0.32, 0.32], [0.16, 0.42], [0.14, 0.66], [0.22, 0.66]]);
      poly([[0.68, 0.32], [0.84, 0.42], [0.86, 0.66], [0.78, 0.66]]);
      poly([[0.4, 0.66], [0.38, 0.95]]); poly([[0.6, 0.66], [0.62, 0.95]]);
    },
    moth() {
      ell(0.5, 0.5, 0.05, 0.22);
      ell(0.5, 0.26, 0.05, 0.05);
      poly([[0.47, 0.22], [0.4, 0.1]]); poly([[0.53, 0.22], [0.6, 0.1]]);
      poly([[0.45, 0.4], [0.12, 0.25], [0.08, 0.5], [0.45, 0.55]], true);
      poly([[0.55, 0.4], [0.88, 0.25], [0.92, 0.5], [0.55, 0.55]], true);
      poly([[0.45, 0.58], [0.2, 0.62], [0.24, 0.8], [0.45, 0.68]], true);
      poly([[0.55, 0.58], [0.8, 0.62], [0.76, 0.8], [0.55, 0.68]], true);
      ell(0.26, 0.4, 0.05, 0.05); ell(0.74, 0.4, 0.05, 0.05); // eye spots
    },
    maldrec() {
      poly([[0.36, 0.1], [0.5, 0.02], [0.64, 0.1], [0.6, 0.2], [0.4, 0.2]], true); // cowl
      ell(0.5, 0.22, 0.085, 0.09);
      dot(0.46, 0.2); dot(0.54, 0.2);
      poly([[0.45, 0.28], [0.55, 0.28]]);               // grim line of a mouth
      poly([[0.4, 0.31], [0.34, 0.6], [0.28, 0.94], [0.72, 0.94], [0.66, 0.6], [0.6, 0.31]], true);
      poly([[0.4, 0.38], [0.18, 0.3]]);                 // raised left hand
      poly([[0.18, 0.3], [0.12, 0.24]]); poly([[0.18, 0.3], [0.12, 0.32]]); poly([[0.18, 0.3], [0.14, 0.38]]);
      poly([[0.6, 0.38], [0.8, 0.44]]);                 // staff hand
      poly([[0.8, 0.1], [0.8, 0.8]]);                   // the Needle staff
      poly([[0.77, 0.13], [0.8, 0.04], [0.83, 0.13]], true);
      // chained verse at the wrist
      ell(0.74, 0.5, 0.025, 0.025); ell(0.7, 0.55, 0.025, 0.025);
      // unsung notes falling
      dot(0.24, 0.5); poly([[0.24, 0.5], [0.24, 0.44]]);
      dot(0.18, 0.62); poly([[0.18, 0.62], [0.18, 0.56]]);
    }
  };
  (fns[id] || fns.humanoid)();
  ctx.restore();
}
